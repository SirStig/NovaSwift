#!/usr/bin/env bash
# Release signing for the Godot desktop auto-updater (see docs/UPDATER.md).
#
#   scripts/release-sign.sh --init
#       ONE TIME. Generates the RSA-4096 update-signing keypair. The PRIVATE key goes to
#       ~/.config/novaswift/update_signing_key.pem (mode 600, outside the repo -- back it up, never commit it);
#       the PUBLIC key is written to godot/updater/update_pubkey.pem and godot/updater/UpdatePubKey.gd, which
#       ship inside the game. Refuses to overwrite an existing private key. Builds made before --init (placeholder
#       key) are "unsigned builds": the updater is disabled in them, so run --init BEFORE building a release.
#
#   scripts/release-sign.sh --version 1.2.0 \
#       --asset linux-x86_64=godot/export/NovaSwift-linux-x86_64.tar.gz \
#       --asset windows-x86_64=godot/export/NovaSwift-windows-x86_64.zip  [--out DIR] [--key PATH] [--min-updater N] [--channel stable|experimental]
#       Builds update.json (version, per-platform asset name / size / sha256 / launcher / required files), signs it
#       (openssl SHA-256 + RSA PKCS#1 v1.5 -- what Godot's Crypto.verify checks), verifies the signature with the
#       public key, and writes update.json + update.json.sig into --out (default: next to the first asset).
#       Upload BOTH files, plus the assets, to the GitHub release tagged v<version>.
#
#   scripts/release-sign.sh --server --version 0.2.0 \
#       --asset linux-x86_64=dist/server/NovaSwiftServer-linux-x86_64.tar.gz \
#       --asset linux-arm64=dist/server/NovaSwiftServer-linux-arm64.tar.gz \
#       --asset macos-arm64=dist/server/NovaSwiftServer-macos-arm64.zip  [--out DIR] [--key PATH]
#       Same RSA key, for the DEDICATED SERVER's self-update: writes server-update.json (version + per-platform asset
#       name / size / sha256) and server-update.json.sig. Upload BOTH next to the archives on the GitHub release tagged
#       server-v<version>. The server refuses to install any release that lacks them or whose signature does not verify
#       (see docs/SECURITY.md, "Self-update").
#
# Needs: openssl, python3 (stdlib only).
set -euo pipefail
cd "$(dirname "$0")/.."

KEY="${NOVASWIFT_UPDATE_KEY:-$HOME/.config/novaswift/update_signing_key.pem}"
PUB_PEM="godot/updater/update_pubkey.pem"
PUB_GD="godot/updater/UpdatePubKey.gd"
MODE=""
SERVER=0
VERSION=""
OUT=""
MIN_UPDATER=1
CHANNEL=""
ASSETS=()

die() { echo "error: $*" >&2; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    --init) MODE=init; shift ;;
    --server) SERVER=1; shift ;;
    --version) VERSION="$2"; MODE="${MODE:-sign}"; shift 2 ;;
    --asset) ASSETS+=("$2"); MODE="${MODE:-sign}"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    --key) KEY="$2"; shift 2 ;;
    --min-updater) MIN_UPDATER="$2"; shift 2 ;;
    --channel) CHANNEL="$2"; shift 2 ;;
    -h|--help) sed -n '2,32p' "$0"; exit 0 ;;
    *) die "unknown argument $1 (try --help)" ;;
  esac
done
[ -n "$MODE" ] || { sed -n '2,32p' "$0"; exit 2; }
command -v openssl >/dev/null || die "openssl not found"
command -v python3 >/dev/null || die "python3 not found"

if [ "$MODE" = init ]; then
  [ ! -e "$KEY" ] || die "$KEY already exists. Refusing to overwrite the signing key (losing or replacing it strands every installed copy)."
  mkdir -p "$(dirname "$KEY")"
  chmod 700 "$(dirname "$KEY")"
  umask 077
  openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:4096 -out "$KEY"
  chmod 600 "$KEY"
  openssl pkey -in "$KEY" -pubout -out "$PUB_PEM"
  python3 - "$PUB_PEM" "$PUB_GD" <<'PY'
import sys
pem = open(sys.argv[1]).read()
assert "BEGIN PUBLIC KEY" in pem
open(sys.argv[2], "w").write(
    "# NOVA Swift updater -- the update-signing PUBLIC key, embedded as a script constant.\n#\n"
    "# GENERATED by scripts/release-sign.sh --init (from godot/updater/update_pubkey.pem). Kept as a .gd so it is\n"
    "# always in the exported .pck (a bare .pem needs an export include_filter). An empty / placeholder value\n"
    "# means \"unsigned build\": the updater is disabled. Never put a private key here.\n"
    "extends RefCounted\n\n"
    'const PEM := """' + pem + '"""\n')
PY
  echo "Private key : $KEY   (mode 600 -- BACK IT UP somewhere safe; never commit it)"
  echo "Public key  : $PUB_PEM and $PUB_GD   (commit these; rebuild the game so it carries them)"
  exit 0
fi

# --- server sign mode ---------------------------------------------------------------------------
if [ "$SERVER" = 1 ]; then
  [ -f "$KEY" ] || die "signing key not found at $KEY (run --init once, or pass --key)"
  [ -n "$VERSION" ] || die "--version X.Y.Z is required"
  [ "${#ASSETS[@]}" -gt 0 ] || die "give at least one --asset <platform>=<file> (linux-x86_64, linux-arm64, macos-arm64, windows-x86_64)"
  grep -q "BEGIN PUBLIC KEY" "$PUB_PEM" || die "$PUB_PEM is still the placeholder: run --init first"
  diff -q <(openssl pkey -in "$KEY" -pubout 2>/dev/null) "$PUB_PEM" >/dev/null \
    || die "$KEY does not match $PUB_PEM -- servers built with that public key would reject this release"
  SRV_VERSION="$(sed -n 's/.*static let current = "\(.*\)".*/\1/p' Sources/NovaSwiftServerCore/GameServer.swift | head -1)"
  [ "$SRV_VERSION" = "$VERSION" ] || die "Sources/NovaSwiftServerCore/GameServer.swift says server version $SRV_VERSION, not $VERSION"
  if [ -z "$OUT" ]; then OUT="$(dirname "${ASSETS[0]#*=}")"; fi
  mkdir -p "$OUT"
  python3 - "$VERSION" "$OUT/server-update.json" "${ASSETS[@]}" <<'PY'
import hashlib, json, os, sys, datetime
version, out = sys.argv[1], sys.argv[2]
OK = {"linux-x86_64", "linux-arm64", "macos-arm64", "windows-x86_64"}
platforms = {}
for spec in sys.argv[3:]:
    key, _, path = spec.partition("=")
    if key not in OK or not os.path.isfile(path):
        sys.exit(f"error: bad --asset {spec!r} (platforms: {', '.join(sorted(OK))}; file must exist)")
    sha = hashlib.sha256(open(path, "rb").read()).hexdigest()
    platforms[key] = {"asset": os.path.basename(path), "size": os.path.getsize(path), "sha256": sha}
    print(f"  {key}: {os.path.basename(path)}  {platforms[key]['size']} bytes  sha256 {sha[:16]}...")
manifest = {"schema": 1, "version": version, "platforms": platforms,
            "published": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")}
with open(out, "w") as f:
    json.dump(manifest, f, indent=2, sort_keys=True); f.write("\n")
PY
  openssl dgst -sha256 -sign "$KEY" -out "$OUT/server-update.json.sig" "$OUT/server-update.json"
  openssl dgst -sha256 -verify "$PUB_PEM" -signature "$OUT/server-update.json.sig" "$OUT/server-update.json" >/dev/null \
    || die "signature self-check failed"
  echo "OK  $OUT/server-update.json"
  echo "OK  $OUT/server-update.json.sig"
  echo "Upload both, plus the archives, to the GitHub release tagged server-v$VERSION."
  exit 0
fi

# --- sign mode ---------------------------------------------------------------------------------
[ -f "$KEY" ] || die "signing key not found at $KEY (run --init once, or pass --key)"
[ -n "$VERSION" ] || die "--version X.Y.Z is required"
# Channel label (signed into update.json; it overrides GitHub's pre-release flag in the game).
if [ -z "$CHANNEL" ]; then case "$VERSION" in *-*) CHANNEL=experimental ;; *) CHANNEL=stable ;; esac; fi
case "$CHANNEL" in stable|experimental) ;; *) die "--channel must be stable or experimental" ;; esac
[ "${#ASSETS[@]}" -gt 0 ] || die "give at least one --asset <platform>=<file>"
grep -q "BEGIN PUBLIC KEY" "$PUB_PEM" || die "$PUB_PEM is still the placeholder: run --init first and rebuild the game"
# The public key in the repo must belong to this private key, or no installed game would accept the update.
diff -q <(openssl pkey -in "$KEY" -pubout 2>/dev/null) "$PUB_PEM" >/dev/null \
  || die "$KEY does not match $PUB_PEM -- games built with that public key would reject this release"
CFG_VERSION="$(sed -n 's/^config\/version="\(.*\)"/\1/p' godot/project.godot)"
[ "$CFG_VERSION" = "${VERSION%%-*}" ] || [ "$CFG_VERSION" = "$VERSION" ] \
  || echo "warning: godot/project.godot config/version is $CFG_VERSION but you are signing $VERSION (the build inside the archive must carry $VERSION)" >&2

if [ -z "$OUT" ]; then OUT="$(dirname "${ASSETS[0]#*=}")"; fi
mkdir -p "$OUT"

python3 - "$VERSION" "$MIN_UPDATER" "$CHANNEL" "$OUT/update.json" "${ASSETS[@]}" <<'PY'
import hashlib, json, os, sys, tarfile, zipfile, datetime
version, min_updater, channel, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
PLATFORMS = {   # platform key -> launcher + files that must exist (relative to the package root)
    "linux-x86_64":   {"launcher": "NovaSwift.sh",  "required": ["NovaSwift.sh", "NovaSwift.x86_64", "NovaSwift.pck"]},
    "windows-x86_64": {"launcher": "NovaSwift.exe", "required": ["NovaSwift.exe", "NovaSwift.pck"]},
}
platforms = {}
for spec in sys.argv[5:]:
    key, _, path = spec.partition("=")
    if key not in PLATFORMS or not os.path.isfile(path):
        sys.exit(f"error: bad --asset {spec!r} (platforms: {', '.join(PLATFORMS)}; file must exist)")
    names = (tarfile.open(path).getnames() if path.endswith((".tar.gz", ".tgz")) else
             zipfile.ZipFile(path).namelist() if path.endswith(".zip") else sys.exit(f"error: {path}: need .tar.gz or .zip"))
    names = [n[2:] if n.startswith("./") else n for n in names]
    names = [n.rstrip("/") for n in names if n.rstrip("/") not in ("", ".")]
    junk = [n for n in names if n.split("/")[-1].startswith("._") or n.startswith("__MACOSX")]
    if junk:   # macOS AppleDouble litter (COPYFILE_DISABLE=1 tar ...): harmless to ignore here, bad to ship
        print(f"  warning: {path} contains macOS metadata files ({junk[0]}, ...); rebuild it with COPYFILE_DISABLE=1", file=sys.stderr)
    names = [n for n in names if n not in junk]
    have = set(names)
    tops = {n.split("/")[0] for n in names}
    wrapper = ""      # a single wrapper folder (NovaSwift/) is fine: the updater descends into it
    if len(tops) == 1 and any(n.startswith(next(iter(tops)) + "/") for n in names):
        wrapper = next(iter(tops)) + "/"
    for req in PLATFORMS[key]["required"]:
        if (wrapper + req) not in have:
            sys.exit(f"error: {path} does not contain {req} -- the updater would reject it")
    sha = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            sha.update(chunk)
    platforms[key] = {"asset": os.path.basename(path), "size": os.path.getsize(path), "sha256": sha.hexdigest(),
                      "launcher": PLATFORMS[key]["launcher"], "required": PLATFORMS[key]["required"]}
    print(f"  {key}: {os.path.basename(path)}  {platforms[key]['size']} bytes  sha256 {sha.hexdigest()[:16]}...")
manifest = {"schema": 1, "version": version, "channel": channel, "min_updater": min_updater,
            "published": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "platforms": platforms}
with open(out, "w") as f:
    json.dump(manifest, f, indent=2, sort_keys=True)
    f.write("\n")
PY

openssl dgst -sha256 -sign "$KEY" -out "$OUT/update.json.sig" "$OUT/update.json"
openssl dgst -sha256 -verify "$PUB_PEM" -signature "$OUT/update.json.sig" "$OUT/update.json" >/dev/null \
  || die "signature self-check failed"
echo "Channel: $CHANNEL (tick \"pre-release\" on GitHub for experimental releases)"
echo "OK  $OUT/update.json"
echo "OK  $OUT/update.json.sig"
echo "Upload update.json, update.json.sig and the asset file(s) to the GitHub release tagged v$VERSION."
