#!/usr/bin/env python3
"""Regenerate Sources/NovaSwiftServerCore/AdminAssets.swift from Sources/NovaSwiftServerCore/Web/*.

The admin panel is plain HTML/CSS/JS (no build step); this embeds it in the binary as Swift string literals so the
server is one self-contained file. Run it after editing anything in Web/ and commit the result.
"""
import pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent / "Sources" / "NovaSwiftServerCore"
files = [("indexHTML", "index.html"), ("appCSS", "app.css"), ("appJS", "app.js"), ("faviconSVG", "favicon.svg")]
out = ["// GENERATED by scripts/embed-server-web.py from Web/. Do not edit by hand.", "enum AdminAssets {"]
for name, fn in files:
    text = (root / "Web" / fn).read_text(encoding="utf-8")
    if '"""#' in text:
        sys.exit(f"{fn} contains the sequence \"\"\"# which cannot be embedded")
    out.append(f'    static let {name} = #"""\n{text}\n"""#')
out.append("}")
(root / "AdminAssets.swift").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote AdminAssets.swift")
