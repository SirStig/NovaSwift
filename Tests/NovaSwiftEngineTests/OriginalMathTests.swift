import XCTest
@testable import NovaSwiftEngine

/// C-1: `Math_AngleFromVector2D` (0x004619b0) against values the original
/// returned under the function oracle (args are `p1 − p2`, screen +y down).
final class OriginalMathTests: XCTestCase {

    func testAnchorsMatchTheOracle() {
        let anchors: [(Float, Float, Int)] = [
            (1, 0, 270), (0, 1, 0), (-1, 0, 90), (0, -1, 180),
            (1, 1, 314), (1, -1, 226), (-1, 1, 46), (-1, -1, 134), (0, 0, 0),
        ]
        for (dx, dy, want) in anchors {
            XCTAssertEqual(OriginalMath.angleFromVector(dx: dx, dy: dy), want, "(\(dx), \(dy))")
        }
    }

    func testTheArctanTableTruncates() {
        XCTAssertEqual(OriginalMath.atanTable[100], 44)
        XCTAssertEqual(OriginalMath.atanTable[50], 26)
    }

    /// A target exactly up-right of the shooter reads 46, not 45; the
    /// report's worked example reads 47 where `floor(atan2)` gives 46.
    func testEngineBearingConvertsToScreenSpace() {
        XCTAssertEqual(OriginalMath.bearing(from: Vec2(0, 0), to: Vec2(1, 1)), 46)
        XCTAssertEqual(OriginalMath.bearing(from: Vec2(0, 0), to: Vec2(0, 10)), 0)
        XCTAssertEqual(OriginalMath.bearing(from: Vec2(0, 0), to: Vec2(10, 0)), 90)
        XCTAssertEqual(OriginalMath.bearing(from: Vec2(0, 0), to: Vec2(1462.5, 1389.7)), 47)
    }

